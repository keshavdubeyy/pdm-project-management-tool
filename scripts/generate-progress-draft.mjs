#!/usr/bin/env node
/**
 * Drafts the next "Project progress" entry (data/progress-updates.json)
 * from git history since the last recorded commit. Run this after pushing
 * code; it never publishes anything by itself.
 *
 *   node scripts/generate-progress-draft.mjs
 *
 * It only reads commit subjects to bucket them into added/improved/fixed/
 * removed — it never invents research, meetings, testing or outcomes, and
 * it never marks anything "published". Review the draft, add any non-code
 * notes and evidence by hand, then flip its "status" to "published".
 * Re-running the script after no new commits is a no-op, and re-running it
 * after more commits updates the same pending draft instead of stacking a
 * duplicate one.
 */
import { execSync } from "node:child_process"
import { readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import path from "node:path"

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const dataPath = path.join(rootDir, "data", "progress-updates.json")
// Keep in sync with PROJECT_START_DATE in lib/progress.ts.
const PROJECT_START_DATE = "2026-08-14"

function todayIso() {
  return new Date().toISOString().slice(0, 10)
}

function daysBetween(fromIso, toIso) {
  const from = new Date(`${fromIso}T00:00:00Z`)
  const to = new Date(`${toIso}T00:00:00Z`)
  return Math.round((to.getTime() - from.getTime()) / 86_400_000)
}

function weekNumberForDate(dateIso) {
  return Math.max(1, Math.floor(daysBetween(PROJECT_START_DATE, dateIso) / 7) + 1)
}

function categorize(subject) {
  const s = subject.toLowerCase()
  if (/^(fix|bugfix|hotfix)(\(.+\))?:/.test(s)) return "fixed"
  if (/^(remove|delete|drop)(\(.+\))?:/.test(s)) return "removed"
  if (/^(refactor|improve|update|perf|style)(\(.+\))?:/.test(s)) return "improved"
  return "added"
}

function readGitHead() {
  return execSync("git rev-parse HEAD", { cwd: rootDir }).toString().trim()
}

function main() {
  let head
  try {
    head = readGitHead()
  } catch {
    console.log(
      "Automatic change detection is not connected here (no git history available).\n" +
        "Add or edit entries directly in data/progress-updates.json instead."
    )
    return
  }

  const data = JSON.parse(readFileSync(dataPath, "utf8"))
  const updates = data.updates ?? []

  const lastPublished = [...updates].reverse().find((u) => u.status === "published")
  const pendingDraft = updates[updates.length - 1]?.status === "draft" ? updates[updates.length - 1] : undefined

  const baselineCommit = pendingDraft?.lastIncludedCommit ?? lastPublished?.lastIncludedCommit
  const periodStart = pendingDraft?.periodStart ?? lastPublished?.periodEnd ?? PROJECT_START_DATE

  if (baselineCommit === head) {
    console.log("No new commits since the last recorded update — nothing to draft.")
    return
  }

  const range = baselineCommit ? `${baselineCommit}..${head}` : head
  const log = execSync(`git log ${range} --reverse --pretty=format:"%h|%s"`, { cwd: rootDir })
    .toString()
    .trim()

  if (!log) {
    console.log("No new commits since the last recorded update — nothing to draft.")
    return
  }

  const buckets = { added: [], improved: [], fixed: [], removed: [] }
  for (const line of log.split("\n")) {
    const [, subject] = line.split("|")
    if (!subject) continue
    buckets[categorize(subject)].push(subject.trim())
  }

  const periodEnd = todayIso()
  const draft = {
    id: `${periodEnd}-draft`,
    status: "draft",
    weekStart: weekNumberForDate(periodStart),
    weekEnd: weekNumberForDate(periodEnd),
    periodStart,
    periodEnd,
    title: "Draft — needs a title and review",
    summary: "Draft — replace with a plain-language summary before publishing.",
    added: buckets.added,
    improved: buckets.improved,
    fixed: buckets.fixed,
    removed: buckets.removed,
    evidence: [],
    lastIncludedCommit: head,
    autoGenerated: true,
  }

  const nextUpdates = pendingDraft ? [...updates.slice(0, -1), draft] : [...updates, draft]
  writeFileSync(dataPath, `${JSON.stringify({ updates: nextUpdates }, null, 2)}\n`)

  console.log(
    `${pendingDraft ? "Updated" : "Added"} a draft entry in data/progress-updates.json ` +
      `(${draft.id}) from ${log.split("\n").length} commit(s).\n` +
      "This only sorted commit subjects into added/improved/fixed/removed — it did not " +
      "record research, meetings, testing or outcomes. Review the draft, write a real title " +
      "and summary, add any manual notes and evidence, then set \"status\" to \"published\"."
  )
}

main()
